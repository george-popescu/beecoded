import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

import {
  CLASSIFICATION_SAMPLE_BYTES,
  CONTENT_TIERS,
  DEFAULT_DISCOVERY_POLICY,
  LOCKFILE_NAMES,
} from './constants.mjs';
import {
  containsSymlink,
  isPathInside,
  isSecretFilename,
  mandatoryPathExclusionReason,
  resolveRepositoryIdentity,
} from './paths.mjs';

function gitFilePaths(repositoryRoot) {
  const result = spawnSync(
    'git',
    [
      '--no-optional-locks',
      '-c',
      'core.fsmonitor=false',
      '-c',
      'core.quotepath=false',
      'ls-files',
      '-z',
      '--cached',
      '--others',
      '--exclude-standard',
    ],
    {
      cwd: repositoryRoot,
      encoding: 'buffer',
      stdio: ['ignore', 'pipe', 'pipe'],
    },
  );
  if (result.status !== 0) {
    throw new Error(`Git file discovery failed: ${result.stderr.toString('utf8').trim()}`);
  }
  return result.stdout
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .sort();
}

export function normalizeDiscoveryPolicy(overrides = {}) {
  const policy = {
    astMaxBytes: overrides.astMaxBytes ?? DEFAULT_DISCOVERY_POLICY.astMaxBytes,
    ftsMaxBytes: overrides.ftsMaxBytes ?? DEFAULT_DISCOVERY_POLICY.ftsMaxBytes,
    sampleBytes: CLASSIFICATION_SAMPLE_BYTES,
  };
  if (!Number.isInteger(policy.astMaxBytes) || policy.astMaxBytes <= 0) {
    throw new Error('astMaxBytes must be a positive integer');
  }
  if (!Number.isInteger(policy.ftsMaxBytes) || policy.ftsMaxBytes <= policy.astMaxBytes) {
    throw new Error('ftsMaxBytes must be a positive integer greater than astMaxBytes');
  }
  return policy;
}

function readFileSample(absolutePath, maximumBytes) {
  const handle = fs.openSync(absolutePath, 'r');
  try {
    const buffer = Buffer.alloc(maximumBytes);
    const bytesRead = fs.readSync(handle, buffer, 0, maximumBytes, 0);
    return buffer.subarray(0, bytesRead);
  } finally {
    fs.closeSync(handle);
  }
}

function isBinarySample(sample) {
  if (sample.includes(0)) return true;
  if (sample.toString('utf8').includes('\uFFFD')) return true;
  let controls = 0;
  for (const byte of sample) {
    if (byte < 32 && ![8, 9, 10, 12, 13].includes(byte)) controls += 1;
  }
  return sample.length > 0 && controls / sample.length > 0.1;
}

function filenameSkipReason(relativePath) {
  const lowerPath = relativePath.toLowerCase();
  const basename = path.posix.basename(lowerPath.replaceAll('\\', '/'));
  if (LOCKFILE_NAMES.has(basename)) return 'lockfile';
  if (/\.(?:cjs|css|js|json|jsx|mjs|ts|tsx)\.map$/.test(basename)) return 'source-map';
  if (/\.min\.(?:cjs|css|js|mjs)$/.test(basename)) return 'minified-content';
  return null;
}

function sampleSkipReason(sample) {
  const text = sample.toString('utf8');
  if (/(?:@generated|auto[- ]generated|generated by|do not edit)/i.test(text.slice(0, 4096))) {
    return 'generated-content';
  }
  if (sample.length >= 4096) {
    const lineBreaks = (text.match(/\n/g) || []).length;
    if (lineBreaks <= 2) return 'minified-content';
  }
  return null;
}

function acceptedFile(relativePath, absolutePath, size, tier, skipReason, sampleBytes) {
  return {
    path: relativePath,
    absolutePath,
    size,
    accepted: true,
    tier,
    skipReason,
    sampleBytes,
  };
}

function rejectedFile(relativePath, skipReason) {
  return {
    path: relativePath,
    accepted: false,
    tier: CONTENT_TIERS.METADATA_ONLY,
    skipReason,
  };
}

function reuseRepositoryFile(repositoryRoot, relativePath, previous) {
  const exclusionReason = mandatoryPathExclusionReason(relativePath);
  if (exclusionReason) return rejectedFile(relativePath, exclusionReason);
  if (isSecretFilename(relativePath)) return rejectedFile(relativePath, 'secret-filename');

  const root = fs.realpathSync(path.resolve(repositoryRoot));
  const absolutePath = path.resolve(root, relativePath);
  if (!isPathInside(root, absolutePath)) {
    return rejectedFile(relativePath, 'outside-root');
  }
  try {
    if (containsSymlink(root, relativePath)) {
      return rejectedFile(relativePath, 'symlink');
    }
  } catch (error) {
    if (error.code === 'ENOENT') return rejectedFile(relativePath, 'deleted');
    throw error;
  }

  const stat = fs.lstatSync(absolutePath);
  if (!stat.isFile()) return rejectedFile(relativePath, 'not-regular-file');
  if (stat.size !== previous.size) return null;
  return acceptedFile(
    relativePath,
    absolutePath,
    stat.size,
    previous.tier,
    previous.skipReason,
    0,
  );
}

export function classifyRepositoryFile(repositoryRoot, relativePath, options = {}) {
  const exclusionReason = mandatoryPathExclusionReason(relativePath);
  if (exclusionReason) return rejectedFile(relativePath, exclusionReason);
  if (isSecretFilename(relativePath)) return rejectedFile(relativePath, 'secret-filename');

  const root = fs.realpathSync(path.resolve(repositoryRoot));
  const absolutePath = path.resolve(root, relativePath);
  if (!isPathInside(root, absolutePath)) {
    return rejectedFile(relativePath, 'outside-root');
  }
  try {
    if (containsSymlink(root, relativePath)) {
      return rejectedFile(relativePath, 'symlink');
    }
  } catch (error) {
    if (error.code === 'ENOENT') return rejectedFile(relativePath, 'deleted');
    throw error;
  }

  const stat = fs.lstatSync(absolutePath);
  if (!stat.isFile()) return rejectedFile(relativePath, 'not-regular-file');

  const filenameReason = filenameSkipReason(relativePath);
  if (filenameReason) {
    return acceptedFile(
      relativePath,
      absolutePath,
      stat.size,
      CONTENT_TIERS.METADATA_ONLY,
      filenameReason,
      0,
    );
  }

  const policy = normalizeDiscoveryPolicy(options.policy);
  const maximumSampleBytes = Math.min(
    stat.size,
    policy.sampleBytes,
    CLASSIFICATION_SAMPLE_BYTES,
  );
  const sample = Buffer.from(
    (options.readSample || readFileSample)(absolutePath, maximumSampleBytes),
  );
  if (isBinarySample(sample)) return rejectedFile(relativePath, 'binary-content');

  const sampleReason = sampleSkipReason(sample);
  if (sampleReason) {
    return acceptedFile(
      relativePath,
      absolutePath,
      stat.size,
      CONTENT_TIERS.METADATA_ONLY,
      sampleReason,
      sample.length,
    );
  }

  if (stat.size > policy.ftsMaxBytes) {
    return acceptedFile(
      relativePath,
      absolutePath,
      stat.size,
      CONTENT_TIERS.METADATA_ONLY,
      'oversized',
      sample.length,
    );
  }
  if (stat.size > policy.astMaxBytes) {
    return acceptedFile(
      relativePath,
      absolutePath,
      stat.size,
      CONTENT_TIERS.FTS_ONLY,
      null,
      sample.length,
    );
  }
  return acceptedFile(
    relativePath,
    absolutePath,
    stat.size,
    CONTENT_TIERS.AST_FTS,
    null,
    sample.length,
  );
}

export function discoverRepository(projectRoot, options = {}) {
  const repository = options.repository || resolveRepositoryIdentity(projectRoot, options);
  if (repository.state !== 'ready') {
    return {
      state: repository.state,
      reason: repository.reason,
      repository,
      files: [],
      skipped: [],
    };
  }

  const previousByPath = new Map(
    (options.previousManifest || []).map((file) => [file.path, file]),
  );
  const changedPaths = options.changedPaths || new Set();
  const classified = gitFilePaths(repository.root)
    .map((relativePath) => {
      const previous = previousByPath.get(relativePath);
      if (previous && !changedPaths.has(relativePath)) {
        const reused = reuseRepositoryFile(repository.root, relativePath, previous);
        if (reused) return reused;
      }
      return classifyRepositoryFile(repository.root, relativePath, options);
    });
  const files = classified.filter((file) => file.accepted);
  const skipped = classified.filter((file) => !file.accepted);

  return {
    state: 'ready',
    reason: null,
    repository,
    policy: normalizeDiscoveryPolicy(options.policy),
    files,
    skipped,
  };
}
