#!/usr/bin/env node

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { performance } from 'node:perf_hooks';
import { fileURLToPath } from 'node:url';

import { createAtlasEvaluationReport } from './atlas/eval.mjs';
import { indexRepository } from './atlas/indexer.mjs';
import { queryAtlas } from './atlas/query.mjs';

function git(root, args) {
  return execFileSync('git', [
    '-c',
    'core.fsmonitor=false',
    '-c',
    'core.preloadindex=false',
    ...args,
  ], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

function write(root, relativePath, content) {
  const destination = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, content);
}

function gitGrep(root, query) {
  const result = spawnSync('git', [
    '-c',
    'core.fsmonitor=false',
    '-c',
    'core.preloadindex=false',
    'grep',
    '-n',
    '-F',
    '-i',
    '-e',
    query,
    '--',
    '*.ts',
  ], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.status !== 0 && result.status !== 1) {
    throw new Error(result.stderr.trim() || 'git grep baseline failed');
  }
  return result.stdout;
}

function baselineSearch(root, query, expectedPaths, clock) {
  const expected = new Set(expectedPaths);
  const start = clock();
  const searchOutput = gitGrep(root, query);
  const matchedPaths = [...new Set(searchOutput
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split(':', 1)[0]))].sort();
  const firstRelevantMs = matchedPaths.some((filePath) => expected.has(filePath))
    ? clock() - start
    : null;
  let filesRead = 0;
  let sourceVerificationCharacters = 0;
  for (const relativePath of expectedPaths) {
    if (!matchedPaths.includes(relativePath)) continue;
    const content = fs.readFileSync(path.join(root, relativePath), 'utf8');
    filesRead += 1;
    sourceVerificationCharacters += content.length;
  }
  return {
    method: 'git-grep-and-direct-source',
    succeeded: expectedPaths.every((filePath) => matchedPaths.includes(filePath)),
    firstRelevantMs,
    matchedFiles: matchedPaths.length,
    filesRead,
    retrievalCharacters: searchOutput.length,
    sourceVerificationCharacters,
    contextCharacters: searchOutput.length + sourceVerificationCharacters,
  };
}

function packetHasPaths(packet, expectedPaths) {
  const paths = new Set(packet.evidence.map((entry) => entry.path));
  return expectedPaths.every((filePath) => paths.has(filePath));
}

export async function runAtlasEvaluation({
  fileCount = 120,
  profile = 'exact-symbol',
  clock = () => performance.now(),
  outputFile = null,
} = {}) {
  if (!Number.isInteger(fileCount) || fileCount < 1) {
    throw new TypeError('fileCount must be a positive integer');
  }
  if (!['exact-symbol', 'broad-service'].includes(profile)) {
    throw new TypeError('profile must be exact-symbol or broad-service');
  }
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), 'nectar-atlas-eval-'));
  const root = path.join(parent, 'repository');
  const cacheRoot = path.join(parent, 'cache');
  fs.mkdirSync(root);
  try {
    git(root, ['init', '-q']);
    git(root, ['config', 'user.email', 'atlas-eval@example.test']);
    git(root, ['config', 'user.name', 'Atlas Eval']);
    const generated = Array.from({ length: fileCount }, (_, index) => (
      `src/modules/module-${String(index).padStart(4, '0')}.ts`
    ));
    for (const [index, relativePath] of generated.entries()) {
      write(
        root,
        relativePath,
        profile === 'broad-service'
          ? [
              '/* @generated by Atlas eval; generic service reference */',
              `export const generated${index} = "fixture-${index}";`,
              '',
            ].join('\n')
          : `export const generated${index} = "fixture-${index}";\n`,
      );
    }
    const expectedPaths = ['src/order-service.test.ts', 'src/order-service.ts'];
    write(root, expectedPaths[0], [
      'import { AtlasTargetService } from "./order-service";',
      'export const targetTest = () => new AtlasTargetService().run();',
      ...Array.from({ length: 80 }, (_, index) => (
        `export const unrelatedTestHelper${index} = () => "test-helper-${index}";`
      )),
      '',
    ].join('\n'));
    write(root, expectedPaths[1], [
      'export class AtlasTargetService {',
      '  run() { return "atlas-eval-target"; }',
      '}',
      ...Array.from({ length: 120 }, (_, index) => (
        `export function unrelatedSourceHelper${index}() { return "source-helper-${index}"; }`
      )),
      '',
    ].join('\n'));
    git(root, ['add', '.']);
    git(root, ['commit', '-qm', 'atlas evaluation fixture']);

    const files = [...generated, ...expectedPaths].sort();
    const query = profile === 'broad-service'
      ? 'service'
      : 'AtlasTargetService';
    const baseline = baselineSearch(root, query, expectedPaths, clock);

    const coldStart = clock();
    const coldIndex = await indexRepository(root, { cacheRoot });
    const coldIndexMs = clock() - coldStart;
    const eligibleIndexedFiles = [
      coldIndex.summary.counts.astFts,
      coldIndex.summary.counts.ftsOnly,
      coldIndex.summary.counts.metadataOnly,
    ].reduce((sum, count) => sum + count, 0);
    if (eligibleIndexedFiles !== files.length) {
      throw new Error(
        `invalid Atlas eval corpus: indexed ${eligibleIndexedFiles} of ${files.length} files`,
      );
    }
    const queryStart = clock();
    let atlasFirstRelevantMs = null;
    const packet = queryAtlas(root, {
      operation: 'context-for-task',
      query,
      cacheRoot,
      limit: 20,
      onEvidence(entry) {
        if (atlasFirstRelevantMs === null && expectedPaths.includes(entry.path)) {
          atlasFirstRelevantMs = clock() - queryStart;
        }
      },
    });
    const queryElapsedMs = clock() - queryStart;
    const atlasSourceVerificationCharacters = expectedPaths.reduce(
      (sum, relativePath) => (
        sum + fs.readFileSync(path.join(root, relativePath), 'utf8').length
      ),
      0,
    );
    fs.appendFileSync(
      path.join(root, expectedPaths[1]),
      'export const incrementalMarker = true;\n',
    );
    const refreshStart = clock();
    await indexRepository(root, { cacheRoot });
    const incrementalRefreshMs = clock() - refreshStart;
    const report = createAtlasEvaluationReport({
      caseId: profile === 'exact-symbol'
        ? `synthetic-typescript-${fileCount}`
        : `synthetic-typescript-broad-service-${fileCount}`,
      expectedPaths,
      baseline,
      atlas: {
        succeeded: (
          packet.state === 'ready'
          && !packet.truncated
          && packetHasPaths(packet, expectedPaths)
        ),
        elapsedMs: queryElapsedMs,
        firstRelevantMs: atlasFirstRelevantMs,
        filesRead: expectedPaths.length,
        sourceVerificationCharacters: atlasSourceVerificationCharacters,
        contextCharacters: (
          JSON.stringify(packet).length + atlasSourceVerificationCharacters
        ),
        incrementalRefreshMs,
        packet,
      },
    });
    const result = {
      ...report,
      methodology: {
        kind: 'synthetic',
        baseline: 'git-grep-and-direct-source',
        contextBoundary: 'retrieval-output-plus-full-selected-source-files',
        corpus: 'same-atlas-eligible-files',
        speedScope: 'synthetic-fixture-only',
        taskProfile: profile,
        ...(profile === 'broad-service'
          ? { noiseProfile: 'generated-source-metadata-only' }
          : {}),
      },
      fixture: {
        files: files.length,
        eligibleIndexedFiles,
        excludedFiles: files.length - eligibleIndexedFiles,
        metadataOnlyFiles: coldIndex.summary.counts.metadataOnly,
        language: 'typescript',
        profile,
      },
      indexing: { coldMs: coldIndexMs, incrementalMs: incrementalRefreshMs },
    };
    if (outputFile) {
      const destination = path.resolve(outputFile);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, `${JSON.stringify(result, null, 2)}\n`);
    }
    return result;
  } finally {
    fs.rmSync(parent, { recursive: true, force: true });
  }
}

export async function runAtlasEvaluationSuite({
  fileCounts = [120, 5_000],
  clock = () => performance.now(),
  outputFile = null,
} = {}) {
  if (
    !Array.isArray(fileCounts)
    || fileCounts.length < 2
    || fileCounts.some((value) => !Number.isInteger(value) || value < 1)
  ) {
    throw new TypeError('fileCounts must contain at least two positive integers');
  }
  const uniqueCounts = [...new Set(fileCounts)].sort((left, right) => left - right);
  if (uniqueCounts.length < 2) {
    throw new TypeError('fileCounts must contain at least two distinct sizes');
  }
  const cases = [];
  for (const fileCount of uniqueCounts) {
    cases.push(await runAtlasEvaluation({ fileCount, clock }));
  }
  const smallProject = cases[0];
  const largeProject = cases.at(-1);
  const broadCase = await runAtlasEvaluation({
    fileCount: uniqueCounts.at(-1),
    profile: 'broad-service',
    clock,
  });
  const report = {
    schema: 1,
    kind: 'atlas-scale-suite',
    tokenEstimation: largeProject.tokenEstimation,
    cases,
    broadCase,
    summary: {
      sameTaskOutcome: [...cases, broadCase]
        .every((entry) => entry.comparison.sameTaskOutcome),
      fullRecall: [...cases, broadCase]
        .every((entry) => entry.atlas.recallAtK === 1),
      smallProject: {
        files: smallProject.fixture.files,
        firstRelevantMsSaved: smallProject.comparison.firstRelevantMsSaved,
        estimatedContextTokensSaved:
          smallProject.comparison.estimatedContextTokensSaved,
        atlasFaster: smallProject.comparison.firstRelevantMsSaved > 0,
      },
      largeProject: {
        files: largeProject.fixture.files,
        firstRelevantMsSaved: largeProject.comparison.firstRelevantMsSaved,
        estimatedContextTokensSaved:
          largeProject.comparison.estimatedContextTokensSaved,
        atlasFaster: largeProject.comparison.firstRelevantMsSaved > 0,
      },
      broadLargeProject: {
        files: broadCase.fixture.files,
        matchedFiles: broadCase.baseline.matchedFiles,
        firstRelevantMsSaved: broadCase.comparison.firstRelevantMsSaved,
        estimatedContextTokensSaved:
          broadCase.comparison.estimatedContextTokensSaved,
        atlasFaster: broadCase.comparison.firstRelevantMsSaved > 0,
      },
    },
  };
  if (outputFile) {
    const destination = path.resolve(outputFile);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, `${JSON.stringify(report, null, 2)}\n`);
  }
  return report;
}

async function main() {
  const outputIndex = process.argv.indexOf('--output');
  const outputFile = outputIndex >= 0 ? process.argv[outputIndex + 1] : null;
  if (outputIndex >= 0 && !outputFile) {
    throw new Error('--output requires a file path');
  }
  const filesIndex = process.argv.indexOf('--files');
  const fileCount = filesIndex >= 0 ? Number(process.argv[filesIndex + 1]) : null;
  if (filesIndex >= 0 && (!Number.isInteger(fileCount) || fileCount < 1)) {
    throw new Error('--files requires a positive integer');
  }
  const report = fileCount === null
    ? await runAtlasEvaluationSuite({ outputFile })
    : await runAtlasEvaluation({ fileCount, outputFile });
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`[nectar-atlas-eval] ${error.message}\n`);
    process.exitCode = 1;
  });
}
